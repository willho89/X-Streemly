#!/usr/bin/env python3
# X-Streemly — generate src/xs_iptv_tables.h from iptv-org's API and playlists
# (CLAUDE.md §5.8).
#
#   python3 -I tools/gen_iptv_tables.py > src/xs_iptv_tables.h
#
# libretro core options hold at most 128 values (RETRO_NUM_CORE_OPTION_VALUES_MAX),
# so the Country option lists the countries with the most channels and the
# Language option the 40 most used languages; categories are all of them but
# XXX (iptv-org distributes no NSFW channels since 2024-01-30; D-011, D-026).
import collections
import datetime
import json
import re
import urllib.request

BASE = "https://iptv-org.github.io"
MAX_COUNTRIES = 126   # + "All countries" + headroom
MAX_LANGUAGES = 40


def get(path):
    with urllib.request.urlopen(BASE + path, timeout=60) as r:
        return r.read().decode("utf-8")


def group_counts(m3u):
    counts = collections.Counter()
    for g in re.findall(r'group-title="([^"]*)"', m3u):
        for part in g.split(";"):
            counts[part] += 1
    return counts


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    countries = json.loads(get("/api/countries.json"))
    languages = json.loads(get("/api/languages.json"))
    categories = json.loads(get("/api/categories.json"))
    by_country = group_counts(get("/iptv/index.country.m3u"))
    by_language = group_counts(get("/iptv/index.language.m3u"))

    name_to_country = {c["name"]: c["code"].lower() for c in countries}
    top_countries = [(name_to_country[n], n) for n, _ in by_country.most_common()
                     if n in name_to_country][:MAX_COUNTRIES]
    top_countries.sort(key=lambda x: x[1])

    name_to_lang = {}
    for l in languages:
        name_to_lang.setdefault(l["name"], l["code"])
    top_langs = [(name_to_lang[n], n) for n, _ in by_language.most_common()
                 if n in name_to_lang][:MAX_LANGUAGES]
    top_langs.sort(key=lambda x: x[1])

    cats = [(c["id"], c["name"]) for c in categories if c["id"] != "xxx"]
    cats.sort(key=lambda x: x[1])

    print("/* Generated by tools/gen_iptv_tables.py on %s from %s: do not edit. */"
          % (datetime.date.today().isoformat(), BASE))
    print("#ifndef XS_IPTV_TABLES_H\n#define XS_IPTV_TABLES_H\n")
    print("/* Countries with the most channels (playlist codes: countries/<code>.m3u). */")
    print("#define XS_IPTV_COUNTRY_VALUES \\")
    print('   { "all", "All countries" }, \\')
    for code, name in top_countries:
        print("   { %s, %s }, \\" % (c_str(code), c_str(name)))
    print("   { NULL, NULL }\n")
    print("/* The most used languages (languages/<code>.m3u). */")
    print("#define XS_IPTV_LANGUAGE_VALUES \\")
    print('   { "any", "Any" }, \\')
    for code, name in top_langs:
        print("   { %s, %s }, \\" % (c_str(code), c_str(name)))
    print("   { NULL, NULL }\n")
    print("/* Categories: value = the name used in group-title. */")
    print("#define XS_IPTV_CATEGORY_VALUES \\")
    print('   { "all", "All" }, \\')
    for _, name in cats:
        print("   { %s, %s }, \\" % (c_str(name), c_str(name)))
    print("   { NULL, NULL }\n")
    print("#endif")


main()
